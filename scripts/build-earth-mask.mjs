// Rasterizes Natural Earth 110m land (public domain) into a bit-packed equirectangular mask.
// Usage: node scripts/build-earth-mask.mjs <ne_110m_land.geojson>
import { readFileSync, writeFileSync } from 'node:fs'

const W = 480
const H = 240
const src = process.argv[2]
if (!src) throw new Error('Pass the path to ne_110m_land.geojson')

const polys = []
for (const f of JSON.parse(readFileSync(src, 'utf8')).features) {
  const g = f.geometry
  if (g.type === 'Polygon') polys.push(g.coordinates)
  else if (g.type === 'MultiPolygon') polys.push(...g.coordinates)
}

// Even-odd over all rings of a polygon (outer ring plus holes).
function inside(rings, lon, lat) {
  let c = false
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i]
      const [xj, yj] = ring[j]
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) c = !c
    }
  }
  return c
}

const bytes = new Uint8Array(Math.ceil((W * H) / 8))
let land = 0
for (let y = 0; y < H; y++) {
  const lat = 90 - ((y + 0.5) / H) * 180
  for (let x = 0; x < W; x++) {
    const lon = -180 + ((x + 0.5) / W) * 360
    if (polys.some((p) => inside(p, lon, lat))) {
      const i = y * W + x
      bytes[i >> 3] |= 1 << (i & 7)
      land++
    }
  }
}

const out = `// GENERATED by scripts/build-earth-mask.mjs from Natural Earth 110m land (public domain). Do not edit.
export const EARTH_MASK_W = ${W}
export const EARTH_MASK_H = ${H}
const DATA = '${Buffer.from(bytes).toString('base64')}'

let bits: Uint8Array | undefined

/** True when the point is land. Longitude -180..180, latitude -90..90, degrees. */
export function isEarthLand(lonDeg: number, latDeg: number): boolean {
  bits ??= Uint8Array.from(atob(DATA), (c) => c.charCodeAt(0))
  const x = Math.min(EARTH_MASK_W - 1, Math.max(0, Math.floor(((lonDeg + 180) / 360) * EARTH_MASK_W)))
  const y = Math.min(EARTH_MASK_H - 1, Math.max(0, Math.floor(((90 - latDeg) / 180) * EARTH_MASK_H)))
  const i = y * EARTH_MASK_W + x
  return (bits[i >> 3]! & (1 << (i & 7))) !== 0
}
`
writeFileSync(new URL('../app/utils/earthMask.ts', import.meta.url), out)
console.log(`land cells: ${land}/${W * H} (${((land / (W * H)) * 100).toFixed(1)}%)`)
